"""v4: background ICE as two streams (Pete, 2026-10-14: what we see is the net of an outside stream and the person's behavior,
larger effects that partly cancel).

  background ICE  y_t = mu_t + r_t + f_t + s_t
    mu_t, sigma_t  the outside stream's expected level and innovation scale, from a recurrent net over EXOGENOUS inputs only
                   (meals, actions, clock, the person's profile): no glucose and no ICE history, so it cannot read its own draws
    r_t            the reaction to the state the person can observe now (glucose level, CGM trend, 30-min projection,
                   heading-low, minutes below 70), a memoryless network: it maps the current state to a push and holds no memory
    f_t, s_t       the latent outside stream's persistence: fast  f_t = phi_f f_{t-1} + sigma_t sqrt(1 - phi_f^2) e
                                                                slow  s_t = phi_s s_{t-1} + sqrt(q_s) e
  Fitted by the exact Kalman-filter likelihood on the real series (missing values only advance the filter), so persistence is
  carried by the latent components and the reaction is only credited with responses to state. Generated by running f and s
  forward as stationary processes: no channel by which the model reads its own output (LESSONS 42-49).
Behavior heads are v3m4's (all inputs, explicit per-person traits).
"""
from __future__ import annotations

import math

import torch
import torch.nn as nn
import torch.nn.functional as F

from .model_v2 import mdn_nll
from .model_v3m import ICEGenV3M4
from .dataset_v3m3 import TARGETS as T3

REACT = ["bg", "bg_ok", "bg_trend", "bg_pred30", "heading_low", "low30", "iob_net"]
# iob_net (pending insulin, FEATURES_M2I/M2V): the reaction sees it, so it can respond to PROJECTED glucose (where glucose is
# heading, LESSONS 69-71); the outside stream does not, so it cannot become a general insulin resistance (LESSONS 68)
OWN = ["bg", "bg_ok", "bg_trend", "bg_pred30", "heading_low", "low30", "bgice", "bgice_ok", "bgice_ema", "bgice_6h", "bgice_24h", "eventual", "iob_net"]


class ICEGenV4(ICEGenV3M4):
    arch = "v4"

    def __init__(self, n_features, n_people, profile_dim=16, hidden=256, layers=2, features=None):
        super().__init__(n_features, n_people, profile_dim, hidden, layers)
        features = list(features) if features is not None else [f"x{i}" for i in range(n_features)]
        self.register_buffer("exo_keep", torch.tensor([0.0 if f in OWN else 1.0 for f in features]))
        self.register_buffer("react_idx", torch.tensor([features.index(f) for f in REACT if f in features], dtype=torch.long))
        self.inp_exo = nn.Linear(n_features + profile_dim, hidden)
        self.gru_exo = nn.GRU(hidden, hidden, num_layers=layers, batch_first=True)
        self.head_mu = nn.Linear(hidden, 2)                            # mu, log sigma (scaled ICE units)
        self.react = nn.Sequential(nn.Linear(len(self.react_idx), 64), nn.Tanh(), nn.Linear(64, 1))
        nn.init.zeros_(self.react[-1].weight); nn.init.zeros_(self.react[-1].bias)
        self.a_f = nn.Parameter(torch.tensor(0.0))                     # phi_f = sigmoid(a_f)
        self.a_s = nn.Parameter(torch.tensor(math.log(0.995 / 0.005)))  # phi_s near 1 (day scale)
        self.b_s = nn.Parameter(torch.tensor(math.log(1e-4)))          # q_s

    def phis(self):
        return torch.sigmoid(self.a_f), torch.sigmoid(self.a_s).clamp(max=0.9999), self.b_s.exp()

    def forward(self, x, person, h=None):
        h1, h2 = h if isinstance(h, tuple) else (None, None)
        out, h1 = super().forward(x, person, h1)
        p = self.profile(person)[:, None, :].expand(-1, x.shape[1], -1)
        z2, h2 = self.gru_exo(torch.relu(self.inp_exo(torch.cat([x * self.exo_keep, p], -1))), h2)
        ms = self.head_mu(z2)
        out["mu"], out["lsig"] = ms[..., 0], ms[..., 1].clamp(-6, 2)
        out["react"] = self.react(x.index_select(-1, self.react_idx))[..., 0]
        out["bgice"] = torch.zeros(x.shape[0], x.shape[1], 3 * self.K_ICE, device=x.device)   # unused (v3m4 heads expect the key)
        return out, (h1, h2)

    def kalman_nll(self, out, y, burn=0):
        """Exact Gaussian likelihood of the observed background ICE y [B, T] (scaled, NaN = missing) under
        y_t = mu_t + r_t + f_t + s_t, f/s AR(1). Returns the mean negative log-likelihood over observed steps after `burn`."""
        phi_f, phi_s, q_s = self.phis()
        mu, sig, r = out["mu"], out["lsig"].exp(), out["react"]
        B, T = y.shape
        m = torch.zeros(B, 2, device=y.device)                          # state mean (f, s)
        P = torch.zeros(B, 2, 2, device=y.device)
        P[:, 0, 0] = sig[:, 0] ** 2; P[:, 1, 1] = q_s / (1 - phi_s ** 2)  # stationary start
        Fm = torch.stack([phi_f, phi_s])
        R = 1e-4
        nll, n = 0.0, 0
        for t in range(T):
            if t > 0:                                                   # predict
                m = m * Fm
                P = P * (Fm[:, None] * Fm[None, :])
                P = P + torch.diag_embed(torch.stack([sig[:, t] ** 2 * (1 - phi_f ** 2), q_s.expand(B)], -1))
            yt = y[:, t]; ok = torch.isfinite(yt)
            if not ok.any():
                continue
            pred = mu[:, t] + r[:, t] + m.sum(-1)
            S = P.sum((-1, -2)) + R
            v = torch.where(ok, yt, pred) - pred
            if t >= burn:
                nll = nll + (0.5 * (torch.log(2 * math.pi * S) + v ** 2 / S))[ok].sum(); n += int(ok.sum())
            K = P.sum(-1) / S[:, None]                                  # P H^T / S, H = [1, 1]
            upd = ok[:, None].float()
            m = m + upd * K * v[:, None]
            P = P - upd[:, :, None] * (K[:, :, None] * P.sum(-2)[:, None, :])
        return nll / max(n, 1)

    def loss(self, out, Y, w=None, w_bgice=False, trait_frac=0.0, trait_sd=1.0):
        """v3m4's behavior losses plus the two-stream Kalman likelihood of background ICE (replacing the MDN term)."""
        o = self.teacher(out, Y)
        y = {k: Y[..., T3.index(k)] for k in T3}
        z = lambda v, m: torch.where(m, v, torch.zeros_like(v))
        parts = {"bgice": self.kalman_nll(out, y["bgice"])}
        ent = y["entry"] > 0.5; new = ent & (y["e_new"] > 0.5); bol = y["bolus"] > 0.5; fb = torch.isfinite(y["bolus"])
        conds = {"meal": torch.isfinite(y["meal"]), "entry": torch.isfinite(y["entry"]), "e_new": ent & torch.isfinite(y["e_new"]),
                 "b_with": ent & fb, "b_alone": ~ent & fb, "b_mode": bol & torch.isfinite(y["b_mode"])}
        tgt = {"b_with": y["bolus"], "b_alone": y["bolus"]}
        for k in self.B:
            c = conds[k]
            if c.any():
                ww = w[c] if (w is not None and k in ("meal", "entry", "b_alone")) else None
                parts[k] = F.binary_cross_entropy_with_logits(o[k][..., 0][c], tgt.get(k, y.get(k))[c], weight=ww)
        given = lambda k: torch.isfinite(y[k]) & (new if k in self.NEW else (y["meal"] > 0.5) if k.startswith("m_") else ent if k.startswith("e_") else bol)
        for k in self.G:
            c = given(k)
            if c.any():
                mu_, ls = o[k].unbind(-1); ls = ls.clamp(-5, 3)
                parts[k] = (0.5 * ((z(y[k], c) - mu_) / ls.exp()) ** 2 + ls)[c].mean()
        for k in self.M:
            c = given(k)
            if c.any():
                parts[k] = mdn_nll(o[k], z(y[k], c), self.K)[c].mean()
        loss = sum(parts.values())
        if trait_frac > 0:
            loss = loss + trait_frac * 0.5 * (self.trait.weight ** 2).sum() / trait_sd ** 2
        return loss, parts

    @torch.no_grad()
    def filter_state(self, out, y):
        """Posterior mean and covariance of (f, s) after the observed series y [1, T] (plant warm-up)."""
        phi_f, phi_s, q_s = self.phis()
        mu, sig, r = out["mu"][0], out["lsig"][0].exp(), out["react"][0]
        m = torch.zeros(2); P = torch.diag(torch.stack([sig[0] ** 2, q_s / (1 - phi_s ** 2)]))
        Fm = torch.stack([phi_f, phi_s])
        for t in range(len(y)):
            if t > 0:
                m = m * Fm; P = P * (Fm[:, None] * Fm[None, :]) + torch.diag(torch.stack([sig[t] ** 2 * (1 - phi_f ** 2), q_s]))
            if torch.isfinite(y[t]):
                S = P.sum() + 1e-4; v = y[t] - (mu[t] + r[t] + m.sum()); K = P.sum(-1) / S
                m = m + K * v; P = P - K[:, None] * P.sum(-2)[None, :]
        return m, P
